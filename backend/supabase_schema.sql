create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
    insert into public.app_users (id, email, full_name)
    values (new.id, new.email, coalesce(new.raw_user_meta_data->>'full_name',''))
    on conflict (id) do nothing;
    return new;
end; $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
    after insert on auth.users for each row execute function public.handle_new_user();

create or replace function public.app_role()
returns text language sql security definer set search_path = public as $$
    select role from public.app_users where id = auth.uid() and is_active = true;
$$;

create or replace function public.is_super_admin()
returns boolean language sql security definer set search_path = public as $$
    select coalesce((select role='super_admin' from public.app_users
                     where id = auth.uid() and is_active = true), false);
$$;

create or replace function public.is_admin()
returns boolean language sql security definer set search_path = public as $$
    select coalesce((select role in ('super_admin','admin') from public.app_users
                     where id = auth.uid() and is_active = true), false);
$$;

create or replace function public.user_assigned_classes()
returns text[] language sql security definer set search_path = public as $$
    select coalesce((select assigned_classes from public.app_users
                     where id = auth.uid() and is_active = true), '{}');
$$;

create or replace function public.user_has_class(class_name text)
returns boolean language sql security definer set search_path = public as $$
    select public.is_admin() or class_name = any(public.user_assigned_classes());
$$;

create or replace function public.has_permission(permission text)
returns boolean language plpgsql security definer set search_path = public as $$
declare
    u public.app_users%rowtype;
begin
    select * into u from public.app_users where id = auth.uid() and is_active = true;
    if u.id is null then return false; end if;
    if u.role in ('super_admin','admin') then return true; end if;
    if u.role <> 'servant' then return false; end if;
    case permission
        when 'attendance' then return coalesce(u.can_record_attendance, false);
        when 'assessments' then return coalesce(u.can_record_assessments, false);
        when 'members' then return coalesce(u.can_manage_members, false);
        when 'reports' then return coalesce(u.can_export_reports, false);
        else return false;
    end case;
end; $$;

