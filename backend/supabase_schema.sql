--  idempotent statement promotes the owner account to Super Admin.
--  Never place a service_role key in the Android app.
-- ============================================================================

update public.app_users
set role = 'super_admin', is_active = true,
    can_record_attendance = true, can_record_assessments = true,
    can_manage_members = true, can_export_reports = true, updated_at = now()
where email = 'abramonetwo@gmail.com';
